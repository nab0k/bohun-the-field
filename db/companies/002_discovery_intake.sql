-- Additive upgrade for EXISTING schema companies; no reset, deletion, company-row creation.
CREATE TABLE IF NOT EXISTS companies.discovery_candidate (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  observation_id bigint NOT NULL REFERENCES companies.observation(id),
  name text NOT NULL, name_norm text NOT NULL, reported_country text,
  website text, role text NOT NULL DEFAULT 'lead',
  status text NOT NULL DEFAULT 'discovered'
    CHECK (status IN ('discovered','candidate_existing','hold','rejected','promotion_ready')),
  matched_company_id text REFERENCES companies.company(id),
  match_reason text, created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(observation_id,name_norm)
);
CREATE INDEX IF NOT EXISTS dc_status ON companies.discovery_candidate(status);
ALTER TABLE companies.run ADD COLUMN IF NOT EXISTS discoveries integer NOT NULL DEFAULT 0;
ALTER TABLE companies.run ADD COLUMN IF NOT EXISTS candidate_existing integer NOT NULL DEFAULT 0;
ALTER TABLE companies.run ADD COLUMN IF NOT EXISTS holds integer NOT NULL DEFAULT 0;
ALTER TABLE companies.discovery_candidate ENABLE ROW LEVEL SECURITY;
ALTER TABLE companies.schema_migration ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON companies.discovery_candidate FROM PUBLIC;
REVOKE ALL ON companies.schema_migration FROM PUBLIC;
